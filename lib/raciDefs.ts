/** 表の列見出しに出す肩書き（メンバー列は個人ではなく役員以外のメンバー全体を指す）。 */
export function raciPersonSubLabel(role: RaciPerson["role"]): string {
  if (role === "leader") return "リーダー";
  if (role === "subleader") return "サブ";
  return "役員以外";
}
