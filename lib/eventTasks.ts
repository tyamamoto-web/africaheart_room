/* ============================================================
   イベント運営マニュアル：当日までの準備と当日の運営タスク
   ------------------------------------------------------------
   出典は TOP に掲載中のイベント告知（lib/data.ts の nextEvent）のみ。
   告知に書かれていない事柄（人数・交通手段の詳細・宿泊・二次会など）は
   推測で足さない。金額・時刻はすべて告知に載っている数字をそのまま使う。

   構造は役員専用ページの表と同じ3階層：
     大分類（時期）→ 中分類（時系列の区切り）→ やること
   id は後から役割（RACI）を紐づけるためのキーなので、文言を直しても変えない。
   役員専用の表は t01〜 を使っているため、こちらは e01〜 で衝突を避ける。
   ============================================================ */

